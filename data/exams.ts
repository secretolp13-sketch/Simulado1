export function getAllQuestions(): Question[] {
  return EXAM_CATEGORIES.flatMap((c) => c.questions);
}

export function getExamById(id: string): ExamCategory | undefined {
  return EXAM_CATEGORIES.find((c) => c.id === id);
}

export function getQuestionsForExam(examId: string): Question[] {
  const exam = getExamById(examId);
  if (!exam) return [];
  // Retorna sempre o caderno completo de 10 questões do exame selecionado
  return exam.questions;
}
